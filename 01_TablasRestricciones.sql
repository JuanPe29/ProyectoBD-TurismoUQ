-- Permite lineas en blanco dentro de las sentencias (SQL*Plus)
SET SQLBLANKLINES ON

--Municipio
CREATE TABLE MUNICIPIO (
    id_municipio NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR2(100) NOT NULL,

    CONSTRAINT pk_municipio
        PRIMARY KEY (id_municipio),

    CONSTRAINT uq_municipio_nombre
        UNIQUE (nombre)
);

--Tipo Alojamiento
CREATE TABLE TIPO_ALOJAMIENTO (
    id_tipo_alojamiento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre               VARCHAR2(100) NOT NULL,
    descripcion          VARCHAR2(500),

    CONSTRAINT pk_tipo_alojamiento
        PRIMARY KEY (id_tipo_alojamiento),

    CONSTRAINT uq_tipo_alojamiento_nombre
        UNIQUE (nombre)
);

--Alojamiento
CREATE TABLE ALOJAMIENTO (
    id_alojamiento      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_municipio        NUMBER NOT NULL,
    id_tipo_alojamiento NUMBER NOT NULL,
    nombre_comercial    VARCHAR2(150) NOT NULL,
    direccion           VARCHAR2(250) NOT NULL,
    estrellas           NUMBER(1) NOT NULL,
    telefono            VARCHAR2(30),
    correo              VARCHAR2(150),

    CONSTRAINT pk_alojamiento
        PRIMARY KEY (id_alojamiento),

    CONSTRAINT fk_alojamiento_municipio
        FOREIGN KEY (id_municipio)
        REFERENCES MUNICIPIO(id_municipio),

    CONSTRAINT fk_alojamiento_tipo
        FOREIGN KEY (id_tipo_alojamiento)
        REFERENCES TIPO_ALOJAMIENTO(id_tipo_alojamiento),

    CONSTRAINT ck_alojamiento_estrellas
        CHECK (estrellas BETWEEN 1 AND 5)
);

--Habitacion
CREATE TABLE HABITACION (
    id_habitacion  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER NOT NULL,
    numero         VARCHAR2(20) NOT NULL,
    capacidad_maxima NUMBER NOT NULL,
    tipo           VARCHAR2(50) NOT NULL,
    descripcion    VARCHAR2(500),

    CONSTRAINT pk_habitacion
        PRIMARY KEY (id_habitacion),

    CONSTRAINT fk_habitacion_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT uq_habitacion_numero
        UNIQUE (id_alojamiento, numero),

    CONSTRAINT ck_habitacion_capacidad
        CHECK (capacidad_maxima > 0),

    CONSTRAINT ck_habitacion_tipo
        CHECK (tipo IN ('Sencilla', 'Doble', 'Suite', 'Cabana'))
);

--Temporada
CREATE TABLE TEMPORADA (
    id_temporada NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR2(100) NOT NULL,
    categoria    VARCHAR2(10) NOT NULL,
    anio         NUMBER(4) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin    DATE NOT NULL,

    CONSTRAINT pk_temporada
        PRIMARY KEY (id_temporada),

    CONSTRAINT ck_temporada_fechas
        CHECK (fecha_fin >= fecha_inicio),

    CONSTRAINT ck_temporada_anio
        CHECK (anio >= 2020),

    CONSTRAINT ck_temporada_categoria
        CHECK (categoria IN ('alta', 'media', 'baja')),

    -- Cada temporada pertenece a un solo anio (Semana Santa 2025 y 2026 son filas distintas)
    CONSTRAINT ck_temporada_mismo_anio
        CHECK (
            EXTRACT(YEAR FROM fecha_inicio) = anio
            AND EXTRACT(YEAR FROM fecha_fin) = anio
        )
);

--Tarifa
CREATE TABLE TARIFA (
    id_tarifa     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_habitacion NUMBER NOT NULL,
    id_temporada  NUMBER NOT NULL,
    precio_noche  NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_tarifa
        PRIMARY KEY (id_tarifa),

    CONSTRAINT fk_tarifa_habitacion
        FOREIGN KEY (id_habitacion)
        REFERENCES HABITACION(id_habitacion),

    CONSTRAINT fk_tarifa_temporada
        FOREIGN KEY (id_temporada)
        REFERENCES TEMPORADA(id_temporada),

    CONSTRAINT uq_tarifa_hab_temporada
        UNIQUE (id_habitacion, id_temporada),

    CONSTRAINT ck_tarifa_precio
        CHECK (precio_noche > 0)
);

--Cliente
CREATE TABLE CLIENTE (
    id_cliente    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(150) NOT NULL,
    documento     VARCHAR2(30) NOT NULL,
    correo        VARCHAR2(150) NOT NULL,
    telefono      VARCHAR2(30),
    ciudad_origen VARCHAR2(100) NOT NULL,

    CONSTRAINT pk_cliente
        PRIMARY KEY (id_cliente),

    CONSTRAINT uq_cliente_documento
        UNIQUE (documento),

    CONSTRAINT uq_cliente_correo
        UNIQUE (correo)
);

--Reserva
CREATE TABLE RESERVA (
    id_reserva    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    NUMBER NOT NULL,
    fecha_reserva DATE NOT NULL,
    fecha_checkin DATE NOT NULL,
    fecha_checkout DATE NOT NULL,
    estado        VARCHAR2(20) NOT NULL,
    fecha_cancelacion DATE,

    CONSTRAINT pk_reserva
        PRIMARY KEY (id_reserva),

    CONSTRAINT fk_reserva_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES CLIENTE(id_cliente),

    CONSTRAINT ck_reserva_fechas
        CHECK (fecha_checkout > fecha_checkin),

    -- La reserva se hace antes (o el mismo dia) del check-in
    CONSTRAINT ck_reserva_fecha_reserva
        CHECK (fecha_reserva <= fecha_checkin),

    -- Solo las reservas canceladas tienen fecha de cancelacion (necesaria para RN07)
    CONSTRAINT ck_reserva_cancelacion
        CHECK (
            (estado = 'cancelada' AND fecha_cancelacion >= fecha_reserva)
            OR (estado <> 'cancelada' AND fecha_cancelacion IS NULL)
        ),

    CONSTRAINT ck_reserva_estado
        CHECK (
            estado IN (
                'pendiente',
                'confirmada',
                'cancelada',
                'completada'
            )
        )
);

--Reserva Habitacion
CREATE TABLE RESERVA_HABITACION (
    id_reserva_habitacion NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reserva            NUMBER NOT NULL,
    id_habitacion         NUMBER NOT NULL,
    fecha_entrada         DATE NOT NULL,
    fecha_salida          DATE NOT NULL,
    num_huespedes         NUMBER NOT NULL,

    CONSTRAINT pk_reserva_habitacion
        PRIMARY KEY (id_reserva_habitacion),

    CONSTRAINT fk_rh_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT fk_rh_habitacion
        FOREIGN KEY (id_habitacion)
        REFERENCES HABITACION(id_habitacion),

    CONSTRAINT uq_reserva_habitacion
        UNIQUE (id_reserva, id_habitacion),

    CONSTRAINT ck_rh_fechas
        CHECK (fecha_salida > fecha_entrada),

    CONSTRAINT ck_rh_huespedes
        CHECK (num_huespedes > 0)
);

--Pago
CREATE TABLE PAGO (
    id_pago    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reserva NUMBER NOT NULL,
    fecha_pago DATE NOT NULL,
    monto      NUMBER(12,2) NOT NULL,
    metodo     VARCHAR2(30) NOT NULL,
    estado     VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_pago
        PRIMARY KEY (id_pago),

    CONSTRAINT fk_pago_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT ck_pago_monto
        CHECK (monto > 0),

    CONSTRAINT ck_pago_metodo
        CHECK (
            metodo IN (
                'tarjeta_credito',
                'tarjeta_debito',
                'PSE',
                'transferencia',
                'efectivo'
            )
        ),

    CONSTRAINT ck_pago_estado
        CHECK (
            estado IN (
                'exitoso',
                'fallido',
                'pendiente',
                'reembolsado'
            )
        )
);

--Servicio
CREATE TABLE SERVICIO (
    id_servicio    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER NOT NULL,
    nombre         VARCHAR2(150) NOT NULL,
    descripcion    VARCHAR2(500),
    precio         NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_servicio
        PRIMARY KEY (id_servicio),

    CONSTRAINT fk_servicio_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT ck_servicio_precio
        CHECK (precio >= 0)
);

--Reserva Servicio
CREATE TABLE RESERVA_SERVICIO (
    id_reserva_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reserva          NUMBER NOT NULL,
    id_servicio         NUMBER NOT NULL,
    cantidad            NUMBER NOT NULL,

    CONSTRAINT pk_reserva_servicio
        PRIMARY KEY (id_reserva_servicio),

    CONSTRAINT fk_rs_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT fk_rs_servicio
        FOREIGN KEY (id_servicio)
        REFERENCES SERVICIO(id_servicio),

    CONSTRAINT uq_reserva_servicio
        UNIQUE (id_reserva, id_servicio),

    CONSTRAINT ck_rs_cantidad
        CHECK (cantidad > 0)
);

--Resena
CREATE TABLE RESENA (
    id_resena    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reserva   NUMBER NOT NULL,
    calificacion NUMBER(1) NOT NULL,
    comentario   VARCHAR2(1000),
    fecha_resena DATE NOT NULL,

    CONSTRAINT pk_resena
        PRIMARY KEY (id_resena),

    CONSTRAINT fk_resena_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT uq_resena_reserva
        UNIQUE (id_reserva),

    CONSTRAINT ck_resena_calificacion
        CHECK (calificacion BETWEEN 1 AND 5)
);

--Usuario
CREATE TABLE USUARIO_SISTEMA (
    id_usuario     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER,
    nombre_usuario VARCHAR2(100) NOT NULL,
    clave          VARCHAR2(255) NOT NULL,
    rol            VARCHAR2(30) NOT NULL,
    estado         VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_usuario_sistema
        PRIMARY KEY (id_usuario),

    CONSTRAINT fk_usuario_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT uq_usuario_nombre
        UNIQUE (nombre_usuario),

    CONSTRAINT ck_usuario_rol
        CHECK (
            rol IN (
                'administrador',
                'encargado'
            )
        ),

    CONSTRAINT ck_usuario_estado
        CHECK (
            estado IN (
                'activo',
                'inactivo'
            )
        ),

    -- El encargado siempre pertenece a un alojamiento; el administrador no
    CONSTRAINT ck_usuario_rol_alojamiento
        CHECK (
            (rol = 'encargado' AND id_alojamiento IS NOT NULL)
            OR (rol = 'administrador' AND id_alojamiento IS NULL)
        )
);

-- Comentarios de cada tabla
