-- Script 04: paquete PKG_TURISMOUQ (funcion, procedimiento y cursor)

SET SQLBLANKLINES ON
SET SERVEROUTPUT ON


-- 1. Tabla con el resultado de la liquidacion mensual
CREATE TABLE LIQUIDACION_MENSUAL (
    id_liquidacion   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento   NUMBER NOT NULL,
    anio             NUMBER(4) NOT NULL,
    mes              NUMBER(2) NOT NULL,
    num_reservas     NUMBER NOT NULL,
    noches_vendidas  NUMBER NOT NULL,
    valor_estadias   NUMBER(14,2) NOT NULL,
    valor_servicios  NUMBER(14,2) NOT NULL,
    valor_total      NUMBER(14,2) NOT NULL,
    comision         NUMBER(14,2) NOT NULL,
    valor_neto       NUMBER(14,2) NOT NULL,
    fecha_generacion DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_liquidacion_mensual
        PRIMARY KEY (id_liquidacion),

    CONSTRAINT fk_liquidacion_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT uq_liquidacion_aloj_mes
        UNIQUE (id_alojamiento, anio, mes),

    CONSTRAINT ck_liquidacion_mes
        CHECK (mes BETWEEN 1 AND 12)
);

COMMENT ON TABLE LIQUIDACION_MENSUAL IS
'Resultado de la liquidacion mensual por alojamiento (PKG_TURISMOUQ.sp_liquidacion_mensual)';


-- 2. Especificacion del paquete
CREATE OR REPLACE PACKAGE PKG_TURISMOUQ AS

    -- Comision de la plataforma
    c_comision CONSTANT NUMBER := 0.10;

    FUNCTION fn_valor_estadia (
        p_id_habitacion IN HABITACION.id_habitacion%TYPE,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER;

    PROCEDURE sp_crear_reserva (
        p_id_cliente    IN  CLIENTE.id_cliente%TYPE,
        p_id_habitacion IN  HABITACION.id_habitacion%TYPE,
        p_fecha_in      IN  DATE,
        p_fecha_out     IN  DATE,
        p_num_huespedes IN  NUMBER,
        p_id_reserva    OUT RESERVA.id_reserva%TYPE
    );

    PROCEDURE sp_liquidacion_mensual (
        p_anio IN NUMBER,
        p_mes  IN NUMBER
    );

    -- Cambios de TARIFA pendientes por auditar (los usan los disparadores)
    TYPE t_cambio_tarifa IS RECORD (
        id_tarifa       TARIFA.id_tarifa%TYPE,
        id_habitacion   TARIFA.id_habitacion%TYPE,
        id_temporada    TARIFA.id_temporada%TYPE,
        operacion       VARCHAR2(10),
        precio_anterior TARIFA.precio_noche%TYPE,
        precio_nuevo    TARIFA.precio_noche%TYPE
    );

    TYPE t_lista_cambios IS TABLE OF t_cambio_tarifa INDEX BY PLS_INTEGER;

    g_cambios_tarifa t_lista_cambios;

END PKG_TURISMOUQ;
/


-- 3. Cuerpo del paquete
CREATE OR REPLACE PACKAGE BODY PKG_TURISMOUQ AS

    -- Valor de la estadia: suma la tarifa de la temporada de cada noche
    FUNCTION fn_valor_estadia (
        p_id_habitacion IN HABITACION.id_habitacion%TYPE,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER
    IS
        v_noche  DATE;
        v_precio TARIFA.precio_noche%TYPE;
        v_total  NUMBER := 0;
    BEGIN
        IF TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
            RAISE_APPLICATION_ERROR(-20001,
                'La fecha de check-out debe ser posterior a la de check-in');
        END IF;

        v_noche := TRUNC(p_fecha_in);

        WHILE v_noche < TRUNC(p_fecha_out) LOOP
            BEGIN
                SELECT ta.precio_noche
                INTO v_precio
                FROM TARIFA ta
                JOIN TEMPORADA te
                    ON te.id_temporada = ta.id_temporada
                WHERE ta.id_habitacion = p_id_habitacion
                  AND v_noche BETWEEN te.fecha_inicio AND te.fecha_fin;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(-20010,
                        'No hay tarifa para la habitacion ' || p_id_habitacion
                        || ' en la noche del ' || TO_CHAR(v_noche, 'DD/MM/YYYY'));
                WHEN TOO_MANY_ROWS THEN
                    RAISE_APPLICATION_ERROR(-20011,
                        'Hay mas de una temporada para la noche del '
                        || TO_CHAR(v_noche, 'DD/MM/YYYY'));
            END;

            v_total := v_total + v_precio;
            v_noche := v_noche + 1;
        END LOOP;

        RETURN v_total;
    END fn_valor_estadia;


    -- Crea una reserva pendiente validando fechas, cliente, habitacion,
    -- capacidad y disponibilidad. No hace COMMIT.
    PROCEDURE sp_crear_reserva (
        p_id_cliente    IN  CLIENTE.id_cliente%TYPE,
        p_id_habitacion IN  HABITACION.id_habitacion%TYPE,
        p_fecha_in      IN  DATE,
        p_fecha_out     IN  DATE,
        p_num_huespedes IN  NUMBER,
        p_id_reserva    OUT RESERVA.id_reserva%TYPE
    )
    IS
        e_fechas_invalidas  EXCEPTION;
        e_checkin_pasado    EXCEPTION;
        e_cliente_no_existe EXCEPTION;
        e_hab_no_existe     EXCEPTION;
        e_capacidad         EXCEPTION;
        e_no_disponible     EXCEPTION;

        v_existe    NUMBER;
        v_capacidad HABITACION.capacidad_maxima%TYPE;
        v_ocupadas  NUMBER;
        v_valor     NUMBER;
    BEGIN
        -- 1. Fechas
        IF TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
            RAISE e_fechas_invalidas;
        END IF;

        IF TRUNC(p_fecha_in) < TRUNC(SYSDATE) THEN
            RAISE e_checkin_pasado;
        END IF;

        -- 2. Cliente
        SELECT COUNT(*)
        INTO v_existe
        FROM CLIENTE
        WHERE id_cliente = p_id_cliente;

        IF v_existe = 0 THEN
            RAISE e_cliente_no_existe;
        END IF;

        -- 3. Habitacion y capacidad
        BEGIN
            SELECT capacidad_maxima
            INTO v_capacidad
            FROM HABITACION
            WHERE id_habitacion = p_id_habitacion;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE e_hab_no_existe;
        END;

        IF p_num_huespedes > v_capacidad THEN
            RAISE e_capacidad;
        END IF;

        -- 4. Disponibilidad
        SELECT COUNT(*)
        INTO v_ocupadas
        FROM RESERVA_HABITACION rh
        JOIN RESERVA r
            ON r.id_reserva = rh.id_reserva
        WHERE rh.id_habitacion = p_id_habitacion
          AND r.estado <> 'cancelada'
          AND rh.fecha_entrada < TRUNC(p_fecha_out)
          AND rh.fecha_salida > TRUNC(p_fecha_in);

        IF v_ocupadas > 0 THEN
            RAISE e_no_disponible;
        END IF;

        -- 5. Valor de la estadia
        v_valor := fn_valor_estadia(p_id_habitacion, p_fecha_in, p_fecha_out);

        -- 6. Registro
        INSERT INTO RESERVA (
            id_cliente, fecha_reserva, fecha_checkin, fecha_checkout, estado
        )
        VALUES (
            p_id_cliente, TRUNC(SYSDATE), TRUNC(p_fecha_in), TRUNC(p_fecha_out), 'pendiente'
        )
        RETURNING id_reserva INTO p_id_reserva;

        INSERT INTO RESERVA_HABITACION (
            id_reserva, id_habitacion, fecha_entrada, fecha_salida, num_huespedes
        )
        VALUES (
            p_id_reserva, p_id_habitacion, TRUNC(p_fecha_in), TRUNC(p_fecha_out), p_num_huespedes
        );

        DBMS_OUTPUT.PUT_LINE('Reserva ' || p_id_reserva || ' creada en estado pendiente. '
            || 'Valor de la estadia: ' || TO_CHAR(v_valor, 'FM999G999G999'));

    EXCEPTION
        WHEN e_fechas_invalidas THEN
            RAISE_APPLICATION_ERROR(-20001,
                'La fecha de check-out debe ser posterior a la de check-in');
        WHEN e_capacidad THEN
            RAISE_APPLICATION_ERROR(-20002,
                'Capacidad excedida: la habitacion ' || p_id_habitacion
                || ' admite maximo ' || v_capacidad || ' huespedes y se pidieron '
                || p_num_huespedes);
        WHEN e_no_disponible THEN
            RAISE_APPLICATION_ERROR(-20003,
                'La habitacion ' || p_id_habitacion || ' no esta disponible entre el '
                || TO_CHAR(p_fecha_in, 'DD/MM/YYYY') || ' y el '
                || TO_CHAR(p_fecha_out, 'DD/MM/YYYY'));
        WHEN e_cliente_no_existe THEN
            RAISE_APPLICATION_ERROR(-20004,
                'El cliente ' || p_id_cliente || ' no existe');
        WHEN e_hab_no_existe THEN
            RAISE_APPLICATION_ERROR(-20005,
                'La habitacion ' || p_id_habitacion || ' no existe');
        WHEN e_checkin_pasado THEN
            RAISE_APPLICATION_ERROR(-20006,
                'No se puede reservar con check-in en una fecha pasada');
    END sp_crear_reserva;


    -- Liquidacion mensual: para cada alojamiento recorre con un cursor
    -- con parametros sus reservas completadas del mes y guarda el total,
    -- la comision y el valor neto.
    PROCEDURE sp_liquidacion_mensual (
        p_anio IN NUMBER,
        p_mes  IN NUMBER
    )
    IS
        CURSOR c_alojamientos IS
            SELECT id_alojamiento, nombre_comercial
            FROM ALOJAMIENTO
            ORDER BY id_alojamiento;

        -- Cursor explicito con parametros
        CURSOR c_reservas (
            p_id_alojamiento NUMBER,
            p_desde          DATE,
            p_hasta          DATE
        ) IS
            SELECT r.id_reserva,
                   SUM(rh.fecha_salida - rh.fecha_entrada) AS noches,
                   SUM(PKG_TURISMOUQ.fn_valor_estadia(rh.id_habitacion,
                                                     rh.fecha_entrada,
                                                     rh.fecha_salida)) AS valor_estadia,
                   (SELECT NVL(SUM(rs.cantidad * s.precio), 0)
                    FROM RESERVA_SERVICIO rs
                    JOIN SERVICIO s
                        ON s.id_servicio = rs.id_servicio
                    WHERE rs.id_reserva = r.id_reserva) AS valor_servicios
            FROM RESERVA r
            JOIN RESERVA_HABITACION rh
                ON rh.id_reserva = r.id_reserva
            JOIN HABITACION h
                ON h.id_habitacion = rh.id_habitacion
            WHERE h.id_alojamiento = p_id_alojamiento
              AND r.estado = 'completada'
              AND r.fecha_checkout >= p_desde
              AND r.fecha_checkout <  p_hasta
            GROUP BY r.id_reserva;

        v_reserva c_reservas%ROWTYPE;

        v_desde           DATE;
        v_hasta           DATE;
        v_num_reservas    NUMBER;
        v_noches          NUMBER;
        v_valor_estadias  NUMBER;
        v_valor_servicios NUMBER;
        v_valor_total     NUMBER;
        v_comision        NUMBER;
        v_alojamientos    NUMBER := 0;
        v_total_mes       NUMBER := 0;
    BEGIN
        IF p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
            RAISE_APPLICATION_ERROR(-20030, 'Mes invalido: ' || p_mes);
        END IF;

        v_desde := TO_DATE(p_anio || '-' || p_mes || '-01', 'YYYY-MM-DD');
        v_hasta := ADD_MONTHS(v_desde, 1);

        DELETE FROM LIQUIDACION_MENSUAL
        WHERE anio = p_anio
          AND mes = p_mes;

        FOR a IN c_alojamientos LOOP

            v_num_reservas    := 0;
            v_noches          := 0;
            v_valor_estadias  := 0;
            v_valor_servicios := 0;

            OPEN c_reservas(a.id_alojamiento, v_desde, v_hasta);
            LOOP
                FETCH c_reservas INTO v_reserva;
                EXIT WHEN c_reservas%NOTFOUND;

                v_num_reservas    := v_num_reservas + 1;
                v_noches          := v_noches + v_reserva.noches;
                v_valor_estadias  := v_valor_estadias + v_reserva.valor_estadia;
                v_valor_servicios := v_valor_servicios + v_reserva.valor_servicios;
            END LOOP;
            CLOSE c_reservas;

            IF v_num_reservas > 0 THEN
                v_valor_total := v_valor_estadias + v_valor_servicios;
                v_comision    := ROUND(v_valor_total * c_comision, 2);

                INSERT INTO LIQUIDACION_MENSUAL (
                    id_alojamiento, anio, mes, num_reservas, noches_vendidas,
                    valor_estadias, valor_servicios, valor_total, comision, valor_neto
                )
                VALUES (
                    a.id_alojamiento, p_anio, p_mes, v_num_reservas, v_noches,
                    v_valor_estadias, v_valor_servicios, v_valor_total, v_comision,
                    v_valor_total - v_comision
                );

                v_alojamientos := v_alojamientos + 1;
                v_total_mes    := v_total_mes + v_valor_total;
            END IF;
        END LOOP;

        COMMIT;

        DBMS_OUTPUT.PUT_LINE('Liquidacion ' || p_mes || '/' || p_anio || ': '
            || v_alojamientos || ' alojamientos liquidados, total facturado '
            || TO_CHAR(v_total_mes, 'FM999G999G999G999'));
    END sp_liquidacion_mensual;

END PKG_TURISMOUQ;
/

